int main() {
    long bad = 0;
    for (int lane = 0; lane < 32; lane++)
        for (int i = 0; i < 16; i++) {
            int got = a_row_of(lane, i) * 32 + a_col_of(lane, i);
            if (got != A_POS[lane * 16 + i]) {
                if (bad < 5)
                    printf("A lane=%d i=%d: yours (r=%d,c=%d), truth (r=%d,c=%d)\n",
                           lane, i, got / 32, got % 32,
                           A_POS[lane * 16 + i] / 32, A_POS[lane * 16 + i] % 32);
                bad++;
            }
        }
    for (int lane = 0; lane < 32; lane++)
        for (int i = 0; i < 8; i++) {
            int got = b_row_of(lane, i) * 8 + b_col_of(lane, i);
            if (got != B_POS[lane * 8 + i]) {
                if (bad < 10)
                    printf("B lane=%d i=%d: yours (k=%d,n=%d), truth (k=%d,n=%d)\n",
                           lane, i, got / 8, got % 8, B_POS[lane * 8 + i] / 8,
                           B_POS[lane * 8 + i] % 8);
                bad++;
            }
        }
    if (bad)
        printf("FAIL: %ld mismatches\n", bad);
    else
        printf("PASS\n");
    return bad != 0;
}
