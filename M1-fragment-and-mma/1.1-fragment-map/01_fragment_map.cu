// lane 被拆成 8 个 four-lane group 和 group 内的 lane。A 的每个 b32
// 保存 K 方向连续的 4 个 fp8；B 的每个 b32 也保存 K 方向连续元素。
static int a_row_of(int lane, int i) {
    return (lane >> 2) + ((i >> 2) & 1) * 8;
}
static int a_col_of(int lane, int i) {
    return (lane & 3) * 4 + (i & 3) + (i >> 3) * 16;
}
static int b_row_of(int lane, int i) {
    return (lane & 3) * 4 + (i & 3) + (i >> 2) * 16;
}
static int b_col_of(int lane, int i) { return lane >> 2; }

